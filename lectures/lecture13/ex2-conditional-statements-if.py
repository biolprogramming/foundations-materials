#!/usr/bin/env python


def main():
    # define some variable x with a value of 4
    x = 4
    # now, let's run some conditional statements:
    if x < 10:
        print("x is less than 10")
    if x > 2 and x < 5:
        print("x is greater than 2 and less than 5")
    if x > 4 or x < 10:
        print("x is greater than 4 OR less than 10")

if __name__ == "__main__":
    main()
